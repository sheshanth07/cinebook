-- Cleanup existing database objects if re-running script
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN 
              ('BOOKING_SEATS', 'BOOKINGS', 'SHOWS', 'SEATS', 'SCREENS', 'THEATRES', 'MOVIES', 'USERS')) 
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. USERS TABLE
-- Stores credentials and user profile information (customers and admins)
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(50)  NOT NULL,
    email         VARCHAR2(100) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    role          VARCHAR2(20)  DEFAULT 'user' NOT NULL,
    created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    
    CONSTRAINT UQ_USERS_EMAIL UNIQUE (email),
    CONSTRAINT CHK_USERS_ROLE CHECK (role IN ('user', 'admin'))
);

-- ----------------------------------------------------------------------------
-- 2. MOVIES TABLE
-- Stores movie catalog information
-- ----------------------------------------------------------------------------
CREATE TABLE MOVIES (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR2(150) NOT NULL,
    description   VARCHAR2(2000),
    genre         VARCHAR2(100) NOT NULL,
    language      VARCHAR2(50)  NOT NULL,
    duration_mins NUMBER(4)     NOT NULL,
    release_date  DATE          NOT NULL,
    certificate   VARCHAR2(10)  DEFAULT 'UA' NOT NULL,
    rating        NUMBER(3,1)   DEFAULT 0.0 NOT NULL,
    cast_details  VARCHAR2(1000),
    director      VARCHAR2(100),
    poster_url    VARCHAR2(500),
    banner_url    VARCHAR2(500),
    is_upcoming   NUMBER(1)     DEFAULT 0 NOT NULL,
    created_at    TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT CHK_MOVIES_DURATION CHECK (duration_mins > 0),
    CONSTRAINT CHK_MOVIES_RATING CHECK (rating >= 0.0 AND rating <= 10.0),
    CONSTRAINT CHK_MOVIES_UPCOMING CHECK (is_upcoming IN (0, 1))
);

-- ----------------------------------------------------------------------------
-- 3. THEATRES TABLE
-- Physical cinema locations
-- ----------------------------------------------------------------------------
CREATE TABLE THEATRES (
    id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR2(150) NOT NULL,
    location VARCHAR2(255) NOT NULL,
    city     VARCHAR2(100) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 4. SCREENS TABLE
-- Auditoriums / screens belonging to theatres
-- ----------------------------------------------------------------------------
CREATE TABLE SCREENS (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theatre_id  NUMBER        NOT NULL,
    screen_name VARCHAR2(100) NOT NULL,
    total_seats NUMBER(4)     NOT NULL,

    CONSTRAINT FK_SCREENS_THEATRE FOREIGN KEY (theatre_id) 
        REFERENCES THEATRES (id) ON DELETE CASCADE,
    CONSTRAINT CHK_SCREENS_SEATS CHECK (total_seats > 0)
);

-- ----------------------------------------------------------------------------
-- 5. SEATS TABLE
-- Physical seat layout within screens
-- ----------------------------------------------------------------------------
CREATE TABLE SEATS (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    screen_id   NUMBER        NOT NULL,
    seat_number VARCHAR2(10)  NOT NULL,
    row_name    VARCHAR2(5)   NOT NULL,
    category    VARCHAR2(20)  DEFAULT 'Regular' NOT NULL,
    base_price  NUMBER(8,2)   NOT NULL,

    CONSTRAINT FK_SEATS_SCREEN FOREIGN KEY (screen_id) 
        REFERENCES SCREENS (id) ON DELETE CASCADE,
    CONSTRAINT UQ_SEATS_SCREEN_NO UNIQUE (screen_id, seat_number),
    CONSTRAINT CHK_SEATS_CATEGORY CHECK (category IN ('Regular', 'Premium')),
    CONSTRAINT CHK_SEATS_PRICE CHECK (base_price > 0)
);

-- ----------------------------------------------------------------------------
-- 6. SHOWS TABLE
-- Showtime schedule linking movie, screen, date, and time
-- ----------------------------------------------------------------------------
CREATE TABLE SHOWS (
    id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id   NUMBER       NOT NULL,
    screen_id  NUMBER       NOT NULL,
    show_date  DATE         NOT NULL,
    show_time  VARCHAR2(10) NOT NULL, -- Format: HH24:MI (e.g., '14:30', '18:45')

    CONSTRAINT FK_SHOWS_MOVIE FOREIGN KEY (movie_id) 
        REFERENCES MOVIES (id) ON DELETE CASCADE,
    CONSTRAINT FK_SHOWS_SCREEN FOREIGN KEY (screen_id) 
        REFERENCES SCREENS (id) ON DELETE CASCADE,
    CONSTRAINT UQ_SHOWS_SCHEDULE UNIQUE (screen_id, show_date, show_time)
);

-- ----------------------------------------------------------------------------
-- 7. BOOKINGS TABLE
-- Customer ticket booking orders
-- ----------------------------------------------------------------------------
CREATE TABLE BOOKINGS (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR2(30)  NOT NULL,
    user_id           NUMBER        NOT NULL,
    show_id           NUMBER        NOT NULL,
    total_amount      NUMBER(10,2)  NOT NULL,
    ticket_count      NUMBER(3)     NOT NULL,
    payment_status    VARCHAR2(20)  DEFAULT 'PENDING' NOT NULL,
    booking_status    VARCHAR2(20)  DEFAULT 'CONFIRMED' NOT NULL,
    created_at        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT UQ_BOOKINGS_REF UNIQUE (booking_reference),
    CONSTRAINT FK_BOOKINGS_USER FOREIGN KEY (user_id) 
        REFERENCES USERS (id) ON DELETE RESTRICT,
    CONSTRAINT FK_BOOKINGS_SHOW FOREIGN KEY (show_id) 
        REFERENCES SHOWS (id) ON DELETE RESTRICT,
    CONSTRAINT CHK_BOOKINGS_TICKETS CHECK (ticket_count > 0),
    CONSTRAINT CHK_BOOKINGS_AMOUNT CHECK (total_amount >= 0),
    CONSTRAINT CHK_BOOKINGS_PAYMENT CHECK (payment_status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED')),
    CONSTRAINT CHK_BOOKINGS_STATUS CHECK (booking_status IN ('CONFIRMED', 'CANCELLED'))
);

-- ----------------------------------------------------------------------------
-- 8. BOOKING_SEATS TABLE
-- Junction table mapping individual booked seats for each show
-- ----------------------------------------------------------------------------
CREATE TABLE BOOKING_SEATS (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     NUMBER       NOT NULL,
    show_id        NUMBER       NOT NULL,
    seat_id        NUMBER       NOT NULL,
    price_snapshot NUMBER(8,2)  NOT NULL,
    status         VARCHAR2(20) DEFAULT 'BOOKED' NOT NULL,

    CONSTRAINT FK_BSEATS_BOOKING FOREIGN KEY (booking_id) 
        REFERENCES BOOKINGS (id) ON DELETE CASCADE,
    CONSTRAINT FK_BSEATS_SHOW FOREIGN KEY (show_id) 
        REFERENCES SHOWS (id) ON DELETE CASCADE,
    CONSTRAINT FK_BSEATS_SEAT FOREIGN KEY (seat_id) 
        REFERENCES SEATS (id) ON DELETE RESTRICT,
    CONSTRAINT CHK_BSEATS_PRICE CHECK (price_snapshot >= 0),
    CONSTRAINT CHK_BSEATS_STATUS CHECK (status IN ('BOOKED', 'CANCELLED'))
);

-- ----------------------------------------------------------------------------
-- CONSTRAINTS & PERFORMANCE INDEXES
-- ----------------------------------------------------------------------------

-- Unique partial index in Oracle to strictly prevent double booking
-- (A seat cannot be actively BOOKED twice for the same show)
CREATE UNIQUE INDEX UQ_ACTIVE_SHOW_SEAT ON BOOKING_SEATS (
    CASE WHEN status = 'BOOKED' THEN show_id ELSE NULL END,
    CASE WHEN status = 'BOOKED' THEN seat_id ELSE NULL END
);

-- Foreign Key Lookup Indexes for high performance
CREATE INDEX IDX_SCREENS_THEATRE ON SCREENS(theatre_id);
CREATE INDEX IDX_SEATS_SCREEN ON SEATS(screen_id);
CREATE INDEX IDX_SHOWS_MOVIE ON SHOWS(movie_id);
CREATE INDEX IDX_SHOWS_SCREEN ON SHOWS(screen_id);
CREATE INDEX IDX_SHOWS_DATE ON SHOWS(show_date);
CREATE INDEX IDX_BOOKINGS_USER ON BOOKINGS(user_id);
CREATE INDEX IDX_BOOKINGS_SHOW ON BOOKINGS(show_id);
CREATE INDEX IDX_BOOKINGS_REF ON BOOKINGS(booking_reference);
CREATE INDEX IDX_BSEATS_BOOKING ON BOOKING_SEATS(booking_id);
CREATE INDEX IDX_BSEATS_SHOW_SEAT ON BOOKING_SEATS(show_id, seat_id);

COMMIT;
